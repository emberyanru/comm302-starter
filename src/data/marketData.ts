// Helper to generate simulated intraday/historical chart candles
function generateHistoricalData(basePrice: number, changePercent: number) {
  const points = 24;
  const data = [];
  const startPrice = basePrice / (1 + changePercent / 100);
  let current = startPrice;
  const now = new Date();

  for (let i = 0; i < points; i++) {
    const time = new Date(now.getTime() - (points - 1 - i) * 60 * 60 * 1000);
    const hourStr = time.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    const volatility = basePrice * 0.003;
    const trend = (basePrice - startPrice) / points;
    const open = current;
    const change = trend + (Math.sin(i / 2) * volatility * 0.8) + ((Math.random() - 0.48) * volatility);
    const close = Math.max(1, open + change);
    const high = Math.max(open, close) + Math.random() * volatility * 0.5;
    const low = Math.min(open, close) - Math.random() * volatility * 0.5;
    const volume = Math.floor(Math.random() * 500000 + 100000);

    data.push({
      time: hourStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume
    });

    current = close;
  }

  // Ensure last close matches basePrice roughly
  data[data.length - 1].close = basePrice;
  return data;
}

